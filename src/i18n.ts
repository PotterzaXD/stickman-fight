const dicts: Record<Lang, Record<Key, string>> = { en, th };

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = dicts[save.data.settings.lang][key] ?? en[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, String(vars[k]));
  return s;
}

export const TEAM_NAMES: Record<Lang, string[]> = {
  en: ['Red', 'Blue', 'Green', 'Yellow'],
  th: ['แดง', 'น้ำเงิน', 'เขียว', 'เหลือง'],
};

export function teamName(i: number): string {
  return TEAM_NAMES[save.data.settings.lang][i] ?? String(i + 1);
}
